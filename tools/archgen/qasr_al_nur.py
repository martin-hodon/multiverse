# ---- the platform's tiles: rectangles cut round holes (pools, parterres, channels)
def tiles(x0, z0, x1, z1, holes):
    xs = sorted({x0, x1, *[c for h in holes for c in (h[0], h[2]) if x0 < c < x1]})
    zs = sorted({z0, z1, *[c for h in holes for c in (h[1], h[3]) if z0 < c < z1]})
    out = []
    for j in range(len(zs) - 1):
        run = None
        for i in range(len(xs) - 1):
            mx, mz = (xs[i] + xs[i + 1]) / 2, (zs[j] + zs[j + 1]) / 2
            free = not any(h[0] < mx < h[2] and h[1] < mz < h[3] for h in holes)
            if free and run is None: run = xs[i]
            if (not free or i == len(xs) - 2) and run is not None:
                out.append((run, zs[j], xs[i + 1] if free else xs[i], zs[j + 1])); run = None
    return out
def split(rects, m=16.0):
    """cut every rectangle into pieces no longer than m (no one triangle of a floor vast)"""
    out = []
    for a, b, c, d in rects:
        nx, nz = max(1, math.ceil((c - a) / m - 1e-6)), max(1, math.ceil((d - b) / m - 1e-6))
        for i in range(nx):
            for j in range(nz):
                out.append((a + (c - a) * i / nx, b + (d - b) * j / nz, a + (c - a) * (i + 1) / nx, b + (d - b) * (j + 1) / nz))
    return out
def slab_rects(name, rects, y, h=SLAB, walked=False, flat=False, about=None, **kw):
    d = {"type": "box", "width": 1, "length": 1, "height": h, "at": []}
    out = []
    groups = {}
    for a, b, c, e in rects:
        groups.setdefault((r4(c - a), r4(e - b)), []).append([r4((a + c) / 2), r4(y), r4((b + e) / 2), 0])
    for k, ((w, l), at) in enumerate(sorted(groups.items())):
        nm = name if k == 0 else f"{name} {k + 1}"
        dd = {"type": "box", "width": w, "length": l, "height": h, "at": at, **kw}
        if walked: dd["walked"] = True
        if flat: dd["flatRoof"] = True
        if about and k == 0: dd["_about"] = about
        out.append(add(nm, dd))
    return out

# ---- a DOG-LEG STAIR: up `rise` from (x, z) along the unit direction yaw, a landing, back beside itself on the side
# `turn` (+1: to the left of the way up, -1 to the right); each storey its own part
def dogleg(name, x, z, yaw, y0, rise, w=1.5, gap=.3, run=.28, about=None, turn=1):
    n = max(2, round(rise / .175)); n += n % 2
    sh = -(w / 2 + gap / 2) * turn
    d = {"type": "staircase", "rise": r4(rise / n), "run": run, "soffit": .3, "flight": n // 2, "width": w,
         "landing": {"depth": 1.8, "width": r4(2 * w + gap), "shift": r4(sh),
                     "then": [{"from": "back", "at": r4(sh), "flight": n // 2, "width": w, "landing": {"depth": 1.0, "width": w}}]},
         "at": [[r4(x), r4(y0), r4(z), r4(yaw)]]}
    if about: d["_about"] = about
    add(name, d)
    L = n // 2 * run + 1.8
    return L, 2 * w + gap

# ---- a DOMED SQUARE ROOM: walls on a square S inside (t thick) up to the pendentives' top, the pendentives springing at
# SPR, and a `drum-dome` on them; `faces` the walls' openings
def domed_room(name, cx, cz, S, t, SPR, faces, dome, y0=0.0, about="", build_=("drum", "dome"), interior=True, fin=None):
    CT = SPR + S / 2
    add(name, {"type": "enclosure", "plan": {"rect": [r4(S + 2 * t), r4(S + 2 * t)]}, "thickness": t, "height": r4(CT + .5), "interior": interior,
               "glass": True, "faces": faces, "openings": [], "at": [[r4(cx), r4(y0), r4(cz), 0]], "_about": about})
    add(name + " pendentives", {"type": "pendentives", "span": S, "springing": SPR, "sides": dome.get("n", 16), "at": [[r4(cx), r4(y0), r4(cz), 0]],
                                "deck": {"thickness": .5, "out": t}})
    add(name + " roof", {"type": "prism", "plan": {"rect": [r4(S + 2 * t + .4), r4(S + 2 * t + .4)], "well": {"radius": r4(S / 2 + dome.get("dt", .6)), "sides": dome.get("n", 16)}},
                         "height": .25, "flatRoof": True, "at": [[r4(cx), r4(y0 + CT + .5), r4(cz), 0]], "_about": "its flat roof round the drum"})
    p = {"R": S / 2, **dome}
    add(name + " dome", comp("components/drum-dome", p, [[r4(cx), r4(y0 + CT + .5), r4(cz), 0]], build=list(build_)))
    top = y0 + CT + .5 + dome["H"]
    R = S / 2 + dome.get("dt", 1.0)
    prof = dome.get("profile", "semicircular")
    h = onion_h(R, dome.get("bulge", 1.2), dome.get("neck", .9)) if prof == "onion" else pointed_h(R, dome.get("spread", .6)) if prof == "pointed" else R
    if fin: finial(name + " finial", cx, top + h - .15, cz, fin)
    return CT, top, top + h

