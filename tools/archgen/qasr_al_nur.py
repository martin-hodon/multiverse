def panel(name, X, Z, yaw, u, n, y, wd, h, dp=.04, about=None, **kw):
    """a thin box on a face: centred u along it, n out from the placement's plane (its middle), its foot at y"""
    lat, nrm = (math.cos(yaw), -math.sin(yaw)), (math.sin(yaw), math.cos(yaw))
    at = [[r4(X + u * lat[0] + n * nrm[0]), r4(y), r4(Z + u * lat[1] + n * nrm[1]), r4(yaw)]]
    d = {"type": "box", "width": r4(wd), "length": r4(dp), "height": r4(h), "at": at, **kw}
    if about: d["_about"] = about
    return d
def pish_dims(W, Hh):
    eb = min(2.4, max(1.3, Hh * .075))                 # the epigraphic band's height
    b = min(1.3, max(.7, W * .045))                    # the border's width
    sw = 2 * (W * .03 + .25)                           # (the corner shafts stand on the border's outer edge: it starts behind them)
    return eb, b, b + sw
