def turned(p, yaw):
    c, s = math.cos(yaw), math.sin(yaw)
    return (r4(p[0] * c + p[1] * s), r4(-p[0] * s + p[1] * c))

def win(at, w, sill, spr, head=SEMI, **kw):
    return {"at": r4(at), "width": w, "sill": sill, "springing": r4(spr), "head": head, **kw}

def door(at, w=1.4, h=2.9, **kw):
    return {"at": r4(at), "width": w, "sill": 0, "springing": r4(h - w / 2), "head": SEMI, "glass": False, **kw}

def wall_at(a, b, t, y):
    L = math.dist(a, b); dx, dz = (b[0] - a[0]) / L, (b[1] - a[1]) / L
    yaw = math.atan2(-dz, dx)
    mx, mz = (a[0] + b[0]) / 2 + t / 2 * math.sin(yaw), (a[1] + b[1]) / 2 + t / 2 * math.cos(yaw)
    return L, [r4(mx), r4(y), r4(mz), r4(yaw)]

def along(a, b, q):
    L = math.dist(a, b); dx, dz = (b[0] - a[0]) / L, (b[1] - a[1]) / L
    return r4((q[0] - (a[0] + b[0]) / 2) * dx + (q[1] - (a[1] + b[1]) / 2) * dz)

def iwall(name, a, b, t, y0, h, tiers, about=None, **kw):
    L, at = wall_at(a, b, t, y0)
    d = {"type": "wall", "width": r4(L), "height": r4(h), "thickness": t, "tiers": tiers, "at": [at], **kw}
    if about: d["_about"] = about
    return add(name, d)

def arc_pts(r, a0, a1, n=8):
    """points on a circle r from angle a0 to a1 (radians from +z toward +x)"""
    return [[r4(r * math.sin(a0 + (a1 - a0) * i / n)), r4(r * math.cos(a0 + (a1 - a0) * i / n))] for i in range(n + 1)]

def face_to(dx, dz):
    """a statue's turn to look along (dx, dz)"""
    return r4(math.atan2(-dz, dx))

