# ---- the balustrades: posts, a top rail, a carved panel, along runs of a line ------------------------------------------------
BAL = {"posts": [], "rails": [], "panels": [], "heads": []}
def balustrade(pts, y, closed=False, H=1.0, step=2.2):
    """a stone balustrade along the polyline pts [(x, z), ...] at height y (its foot); posts every `step` or less"""
    runs = list(zip(pts, pts[1:])) + ([(pts[-1], pts[0])] if closed else [])
    for (ax, az), (bx, bz) in runs:
        L = math.hypot(bx - ax, bz - az)
        if L < .3: continue
        n = max(1, round(L / step))
        BAL["rails"].append([r4(ax), r4(y + H - .1), r4(az), r4(bx), r4(y + H - .1), r4(bz)])
        BAL["panels"].append([r4(ax), r4(y + .42), r4(az), r4(bx), r4(y + .42), r4(bz)])
        for j in range(n + 1):
            x, z = ax + (bx - ax) * j / n, az + (bz - az) * j / n
            BAL["posts"].append([r4(x), r4(y), r4(z), r4(x), r4(y + H + .12), r4(z)])
            BAL["heads"].append([r4(x), r4(y + H + .12), r4(z), r4(x), r4(y + H + .36), r4(z)])
def balustrade_rect(x0, z0, x1, z1, y, gaps=(), H=1.0):
    """round a rectangle, leaving `gaps` [(side, at, width)]: side "s" (+z), "n", "e" (+x), "w"; at along it from its middle"""
    sides = {"s": ((x0, z1), (x1, z1)), "n": ((x1, z0), (x0, z0)), "e": ((x1, z1), (x1, z0)), "w": ((x0, z0), (x0, z1))}
    for s, (a, b) in sides.items():
        L = math.hypot(b[0] - a[0], b[1] - a[1]); ux, uz = (b[0] - a[0]) / L, (b[1] - a[1]) / L
        cuts = sorted([(L / 2 + (g[1] if s in "sw" else -g[1]) - g[2] / 2, L / 2 + (g[1] if s in "sw" else -g[1]) + g[2] / 2) for g in gaps if g[0] == s])
        t = 0.0
        for c0, c1 in cuts + [(L, L)]:
            if c0 - t > .3: balustrade([(a[0] + ux * t, a[1] + uz * t), (a[0] + ux * c0, a[1] + uz * c0)], y, H=H)
            t = c1

