def flight(name, x, z, d, y0, y1, w, run=0.30, rise=.16, about=None, **kw):
    """a straight flight `w` wide whose TOP edge's middle is (x, z), climbing toward `d` ("+x", "-x", "+z", "-z") from y0 to y1"""
    n = max(2, math.ceil((y1 - y0) / rise - 1e-6)); L = n * run
