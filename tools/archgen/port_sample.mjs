// node tools/archgen/port_sample.mjs -- one sample harbour per tradition, laid out by port.js on a straight shore
// and written as an architecture definition of `component` parts: assets/architecture/harbour/<finish>.json.
// The shore runs along x, the sea is +z, the quay top y 0 (the frame every harbour piece shares); berths and the
// street are `berth` / `path` markers. The finish of the same name (finishes/<finish>.json, by harbour.py) dresses it.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { layoutPort, portCulture } from "../../port.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const table = JSON.parse(fs.readFileSync(path.join(ROOT, "assets/world/ports.json"), "utf8"));
const r3 = (v) => Math.round(v * 1000) / 1000;
const SAMPLES = [   // [culture, seed]: one per finish
  ["greek", 3], ["roman", 5], ["medieval", 3], ["chinese", 4], ["japanese", 2], ["industrial", 3], ["maya", 2], ["ottoman", 4], ["egyptian", 3]];
const out = path.join(ROOT, "assets/architecture/harbour");
fs.mkdirSync(out, { recursive: true });

for (const [culture, seed] of SAMPLES) {
  const C = portCulture(table, culture), F = C.quay?.F ?? 1.6, L = (C.length ?? 140) + 30;
  const points = []; for (let x = -L / 2; x <= L / 2 + 1e-6; x += 5) points.push([x, 0]);
  const lay = layoutPort({ points, heading: 0, level: -F, period: culture, seed, table, gate: [8, -70] });
  const key = lay.finish.split("/").pop();
  const parts = {}, count = {};
  let b = [1e9, -1e9, 1e9, -1e9];
  for (const p of lay.placements) {
    const n = (count[p.role] = (count[p.role] ?? 0) + 1), name = `${p.role} ${n}`;
    parts[name] = { type: "component", use: p.def, params: p.params, at: [[p.x, r3(p.y), p.z, p.yaw]] };
    for (const [sx, sz] of [[-1, -1], [1, -1], [1, 1], [-1, 1]]) {
      const x = sx * p.w / 2, z = sz * p.d / 2, c = Math.cos(p.yaw), s = Math.sin(p.yaw);
      const X = p.x + x * c + z * s, Z = p.z - x * s + z * c;
      b = [Math.min(b[0], X), Math.max(b[1], X), Math.min(b[2], Z), Math.max(b[3], Z)];
    }
  }
  lay.berths.forEach((B, i) => {
    const mx = (B.a[0] + B.b[0]) / 2, mz = (B.a[1] + B.b[1]) / 2, yaw = Math.atan2(B.b[0] - B.a[0], B.b[1] - B.a[1]);
    parts[`berth ${i + 1}`] = { type: "marker", role: "berth", at: [[r3(mx), r3(-F), r3(mz), r3(yaw)]],
                                 data: { kind: B.kind, length: B.length, depth: B.depth, out: B.out } };
  });
  lay.path.forEach((q, i) => { parts[`path ${i}`] = { type: "marker", role: "path", at: [[q[0], 0, q[1], 0]], data: { i } }; });
  const doc = {
    name: `${C.finish ? (JSON.parse(fs.readFileSync(path.join(ROOT, "assets", C.finish + ".json"), "utf8")).name) : culture}`,
    _about: `GENERATED by tools/archgen/port_sample.mjs: port.js's layout of a ${culture} harbour (seed ${seed}) on a straight shore -- ` +
            `the shore along x, the sea +z, the quay top y 0, the water at y -${F}. ${lay.placements.length} pieces, ${lay.berths.length} berths` +
            (lay.dropped.length ? `; did not fit: ${lay.dropped.join(", ")}` : "") + ".",
    site: { origin: true },
    params: { detail: 4, footW: r3(b[1] - b[0]), footD: r3(b[3] - b[2]) },
    parts,
    build: Object.keys(parts),
  };
  fs.writeFileSync(path.join(out, key + ".json"), JSON.stringify(doc, null, 1) + "\n");
  console.log(`harbour/${key}`.padEnd(30), culture.padEnd(11), `${lay.placements.length} pieces, ${lay.berths.length} berths, dropped [${lay.dropped}]`);
}
