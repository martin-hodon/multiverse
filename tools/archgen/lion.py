#!/usr/bin/env python3
# THE COUCHANT LION (2026-11-03): a stone lion lying on its plinth, head raised, forepaws stretched before it -- the
# guardian of a stair or a gate (the Parliament's on Kossuth Square, Béla Markup 1902; a bridgehead's, a palace's). Carved
# as the Sphinx is (giza.json): lofts -- the body, the folded haunches and the hind paws beside it, the forelegs, the mane's
# ruff round the neck, the head and its muzzle, the tail laid round the flank. In units of its length (rump to the paws'
# tips) times `S`; +z its front, standing on the plinth's top.
#   python3 tools/archgen/lion.py   ->   assets/architecture/components/couchant-lion.json
import os, json

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
r4 = lambda v: round(v, 4)
S = lambda v: f"{r4(v)} * S" if v else 0                       # a length in the lion's units
LIFT = "plinthH"                                               # (everything stands on the plinth's top)


def sec(s, u, v, a, b, n=2.2, b2=None):
    q = {"s": S(s), "u": S(u), "v": S(v), "a": S(a), "b": S(b), "n": n}
    if b2 is not None: q["b2"] = S(b2)
    return q


def loft(secs, sides=14, smooth=2, about=None):
    d = {"type": "loft", "axis": "z", "sides": sides, "smooth": smooth, "sections": secs, "at": [[0, LIFT, 0, 0]]}
    if about: d["_about"] = about
    return d


parts, build = {}, []
def add(n, d): parts[n] = d; build.append(n)

add("plinth", {"type": "box", "width": "S * 0.62", "length": "S * 1.12", "height": "plinthH", "at": [[0, 0, 0, 0]],
               "_about": "the block it lies on"})
add("body", loft([sec(-.49, 0, .17, .03, .04), sec(-.45, 0, .2, .15, .16), sec(-.33, 0, .21, .19, .2), sec(-.14, 0, .2, .16, .18),
                  sec(.04, 0, .24, .18, .23), sec(.13, 0, .27, .15, .22), sec(.18, 0, .3, .05, .07)], sides=18, smooth=3,
                 about="the body lying along the plinth: the rump, the lean waist, the deep chest"))
for side, sx in (("right", 1), ("left", -1)):
    add(f"haunch {side}", loft([sec(-.46, sx * .14, .2, .02, .05), sec(-.39, sx * .16, .2, .08, .15), sec(-.27, sx * .18, .16, .08, .14),
                                sec(-.15, sx * .2, .07, .06, .07), sec(-.03, sx * .2, .04, .055, .04), sec(.02, sx * .2, .035, .02, .02)],
                               about="the haunch and the hind leg folded along the flank, the hind paw by the elbow"))
    add(f"foreleg {side}", loft([sec(.0, sx * .13, .17, .05, .1), sec(.1, sx * .13, .1, .07, .1), sec(.2, sx * .13, .06, .06, .06),
                                 sec(.38, sx * .12, .05, .055, .05), sec(.46, sx * .12, .045, .065, .045), sec(.5, sx * .12, .04, .02, .02)],
                                about="the foreleg stretched forward, the paw broad on the plinth"))
add("mane", loft([sec(-.05, 0, .27, .13, .13, 1.8), sec(.05, 0, .33, .22, .22, 1.8, b2=.3), sec(.15, 0, .41, .23, .24, 1.8, b2=.3),
                  sec(.23, 0, .46, .16, .17, 1.8), sec(.27, 0, .47, .05, .05, 1.8)], sides=16,
                 about="the mane's ruff round the neck and the head, down over the chest and the shoulders"))
add("head", loft([sec(.21, 0, .47, .11, .11, 2.4), sec(.29, 0, .465, .115, .11, 2.4), sec(.34, 0, .45, .1, .095, 2.4), sec(.385, 0, .425, .08, .07, 2.6),
                  sec(.41, 0, .415, .07, .06, 2.6), sec(.425, 0, .41, .02, .02)], sides=14,
                 about="the head held up over the paws: the broad brow, the short square muzzle"))
add("tail", loft([sec(-.5, .04, .12, .025, .025, 2), sec(-.46, .17, .04, .025, .025, 2), sec(-.3, .25, .028, .022, .022, 2),
                  sec(-.12, .25, .03, .022, .022, 2), sec(-.06, .24, .035, .04, .035, 2), sec(-.03, .24, .035, .01, .01, 2)], sides=10,
                 about="the tail laid round the right flank, its tuft by the hind paw"))

doc = {"name": "Couchant lion",
       "_about": "A COUCHANT LION: a stone lion lying on its plinth, head raised, forepaws stretched before it -- the guardian of a stair or a gate (the Parliament's on Kossuth Square). Carved in lofts as the Sphinx is: the body, the folded haunches, the forelegs, the mane's ruff, the head and muzzle, the tail round the flank. `S` its length, rump to the paws' tips; it faces +z. Generated by tools/archgen/lion.py.",
       "params": {"detail": 4, "S": 2.2, "_S": "its length, rump to the paws' tips (metres)", "plinthH": 1.4, "_plinthH": "the plinth's height"},
       "build": build, "parts": parts}
open(os.path.join(ROOT, "assets/architecture/components/couchant-lion.json"), "w").write(json.dumps(doc, indent=2) + "\n")
print("couchant-lion:", len(parts), "parts")
